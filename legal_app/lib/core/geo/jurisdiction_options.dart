  static List<String>? forCountry(String? countryCode) {
    if (countryCode == null || countryCode.isEmpty) return null;
    final code = countryCode.toUpperCase();
    if (code == 'US') return usJurisdictions;
    return _countryStates[code];
  }

  static bool hasDropdown(String? countryCode) =>
      forCountry(countryCode) != null;

  static String dropdownLabel(String? countryCode) {
    final code = countryCode?.toUpperCase();
    if (code == 'KE') return 'County (optional)';
    return 'State / region (optional)';
  }
