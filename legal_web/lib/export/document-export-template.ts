/** Build the Word-compatible HTML blob for .doc export. */
export function buildWordExportHtml(
  title: string,
  content: string,
  meta: ExportMeta,
  branding: ExportBrandingInput,
): string {
  const date =
    meta.date ??
    new Date().toLocaleDateString("en-IN", { year: "numeric", month: "long", day: "numeric" })

  const htmlContent = markdownToHtml(content)
  const watermarkHtml = meta.watermark
    ? `<div class="watermark">${escapeHtml(meta.watermark)}</div>`
    : ""

  const citationsHtml =
    meta.citations && meta.citations.length > 0
      ? `<div class="citations"><h3>References</h3><ul>${meta.citations.map((c) => `<li>${escapeHtml(c)}</li>`).join("")}</ul></div>`
      : ""

  const toaHtml =
    meta.tableOfAuthorities && meta.tableOfAuthorities.length > 0
      ? `<div class="citations"><h3>Table of Authorities</h3><ul>${meta.tableOfAuthorities.map((c) => `<li>${escapeHtml(c)}</li>`).join("")}</ul></div>`
      : ""

  const disclaimerText =
    meta.disclaimer ??
    "This document is generated by Umbrella Legal AI and is for informational purposes only. It is not legal advice. Always consult a qualified advocate before taking any legal action."

  const firmLogoHtml = branding.firmLogoDataUri
    ? `&nbsp;&nbsp;<img src="${branding.firmLogoDataUri}" alt="Firm logo" style="height:30pt;width:auto;max-width:120pt;vertical-align:middle;object-fit:contain;" />`
    : ""

  return `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word" xmlns="http://www.w3.org/TR/REC-html40">
<head>
  <meta charset="UTF-8">
  <title>${escapeHtml(title)}</title>
  <!--[if gte mso 9]><xml><w:WordDocument><w:View>Print</w:View><w:Zoom>90</w:Zoom></w:WordDocument></xml><![endif]-->
  <style>
    body { font-family: Calibri, Arial, sans-serif; font-size: 11pt; color: #111827; margin: 40pt 50pt; }
    h1 { font-size: 16pt; font-weight: bold; color: #1f2937; margin-bottom: 6pt; }
    h2 { font-size: 13pt; font-weight: bold; color: #1f2937; margin-top: 16pt; margin-bottom: 4pt; border-bottom: 1pt solid #e5e7eb; padding-bottom: 3pt; }
    h3 { font-size: 11pt; font-weight: bold; color: #374151; margin-top: 10pt; margin-bottom: 3pt; }
    h4 { font-size: 10pt; font-weight: bold; color: #6b7280; margin-top: 8pt; }
    p { margin-bottom: 8pt; line-height: 1.5; }
    li { margin-left: 20pt; margin-bottom: 3pt; }
    .meta-row { font-size: 9pt; color: #6b7280; margin-bottom: 4pt; }
    .query-box { background: #f3f4f6; border-left: 3pt solid #4f46e5; padding: 8pt 10pt; margin-bottom: 18pt; font-size: 10pt; color: #374151; }
    .disclaimer { background: #fffbeb; border: 1pt solid #fde68a; padding: 8pt 10pt; font-size: 9pt; color: #92400e; margin-top: 18pt; }
    .footer { font-size: 9pt; color: #9ca3af; margin-top: 24pt; border-top: 1pt solid #e5e7eb; padding-top: 8pt; }
    .watermark { position: fixed; top: 45%; left: 50%; transform: translate(-50%, -50%) rotate(-24deg); font-size: 36pt; font-weight: bold; letter-spacing: .12em; color: #f3d5a5; text-transform: uppercase; }
  </style>
</head>
<body>
  ${watermarkHtml}
  <p>
    <img src="${branding.umbrellaLogoSrc}" alt="Umbrella" style="height:30pt;width:auto;max-width:160pt;vertical-align:middle;object-fit:contain;" />
    ${firmLogoHtml}
  </p>
  <p class="meta-row">${escapeHtml(date)}${meta.countryCode ? ` · Jurisdiction: ${escapeHtml(meta.countryCode)}` : ""}</p>
  <hr style="border: none; border-top: 1.5pt solid #4f46e5; margin-bottom: 16pt;">
  <h1>${escapeHtml(title)}</h1>
  ${meta.query ? `<div class="query-box"><strong>Query:</strong> ${escapeHtml(meta.query)}</div>` : ""}
  <p>${htmlContent}</p>
  ${toaHtml}
  ${citationsHtml}
  <div class="disclaimer">${escapeHtml(disclaimerText)}</div>
  <p class="footer">Generated by Umbrella Legal AI · ${escapeHtml(date)}</p>
</body>
</html>`
}
