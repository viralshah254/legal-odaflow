for (const locale of TARGET_LOCALES) {
  const tr = TRANSLATIONS[locale]
  if (!tr) {
    console.error(`Missing translations for ${locale}`)
    process.exit(1)
  }
  for (const key of enKeys) {
    if (!tr[key]) {
      console.error(`${locale}: missing key ${key}`)
      process.exit(1)
    }
  }
  const outPath = path.join(SHARED, locale, 'accessibility.json')
  fs.writeFileSync(outPath, JSON.stringify(tr, null, 2) + '\n')
  console.log(`Wrote ${outPath}`)
}

