import {
  IsEmail,
  IsIn,
  IsOptional,
  IsString,
  MaxLength,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { Type } from 'class-transformer';
import type { StartWorkMode } from './work-context.service';

export class CreateClientDto {
  @IsString()
  @MinLength(1)
  @MaxLength(200)
  name!: string;

  @IsOptional()
  @IsEmail()
  email?: string;

  @IsOptional()
  @IsString()
  @MaxLength(40)
  phone?: string;

  @IsOptional()
  @IsString()
  @MinLength(2)
  @MaxLength(2)
  countryCode?: string;
}

export class CreateMatterDto {
  @IsString()
  @MinLength(1)
  @MaxLength(300)
  title!: string;

  @IsOptional()
  @IsString()
  @MaxLength(120)
  jurisdiction?: string;

  @IsOptional()
  @IsString()
  @MaxLength(80)
  matterType?: string;

  @IsOptional()
  @IsString()
  @MinLength(2)
  @MaxLength(2)
  countryCode?: string;
}

export class StartWorkRequestDto {
  @IsIn(['existing_client', 'new_client', 'unassigned'])
  mode!: StartWorkMode;

  @IsOptional()
  @IsString()
  clientId?: string;

  @IsOptional()
  @IsString()
  matterId?: string;

  @IsOptional()
  @ValidateNested()
  @Type(() => CreateClientDto)
  createClient?: CreateClientDto;

  @IsOptional()
  @ValidateNested()
  @Type(() => CreateMatterDto)
  createMatter?: CreateMatterDto;

  @IsOptional()
  @IsString()
  @MaxLength(64)
  idempotencyKey?: string;

  /**
   * Per-intent operation key for retry/reconnect safety.
   * Must be unique per user intent (e.g. UUID v4 generated by the client).
   * Different from `idempotencyKey` which scopes to client/matter identity;
   * this key scopes to the specific operation type (draft, research, etc.)
   * so retries don't create duplicate operations.
   */
  @IsOptional()
  @IsString()
  @MaxLength(64)
  operationRequestKey?: string;

  /** Explicit ISO country when not inferrable from client/matter. */
  @IsOptional()
  @IsString()
  @MinLength(2)
  @MaxLength(2)
  countryCode?: string;
}
