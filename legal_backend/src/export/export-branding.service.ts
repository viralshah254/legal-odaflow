import { Injectable } from '@nestjs/common';
import * as fs from 'fs';
import * as path from 'path';
import { PrismaService } from '@/prisma/prisma.service';
import { S3UploadService } from '@/storage/s3-upload.service';

export interface ExportBranding {
  umbrellaLogoDataUri: string;
  firmLogoDataUri: string | null;
  firmDisplayName: string | null;
}

interface DocumentBrandingSettings {
  showLogoOnExports?: boolean;
}

@Injectable()
export class ExportBrandingService {
  private umbrellaLogoCache: string | null = null;

  constructor(
    private readonly prisma: PrismaService,
    private readonly s3: S3UploadService,
  ) {}

  /** Load branding for a tenant: Umbrella logo (always) + optional firm logo. */
  async getBranding(tenantId: string): Promise<ExportBranding> {
    const umbrellaLogoDataUri = await this.getUmbrellaLogoDataUri();

    const firmProfile = await this.prisma.firmProfile.findUnique({
      where: { tenantId },
    });

    const settings = firmProfile?.settings as
      | { documentBranding?: DocumentBrandingSettings }
      | null;
    const showFirmLogo =
      settings?.documentBranding?.showLogoOnExports === true &&
      Boolean(firmProfile?.logoUrl);

    let firmLogoDataUri: string | null = null;
    if (showFirmLogo && firmProfile?.logoUrl) {
      firmLogoDataUri = await this.fetchLogoAsDataUri(firmProfile.logoUrl).catch(
        () => null,
      );
    }

    return {
      umbrellaLogoDataUri,
      firmLogoDataUri,
      firmDisplayName: firmProfile?.displayName ?? null,
    };
  }

  /** Build the letterhead HTML snippet injected at the top of every document. */
  buildLetterheadHtml(
    branding: ExportBranding,
    meta: { date: string; jurisdiction?: string; title?: string; query?: string },
  ): string {
    const firmLogoHtml = branding.firmLogoDataUri
      ? `<img src="${branding.firmLogoDataUri}" alt="Firm logo" class="firm-logo" />`
      : '';

    const queryHtml = meta.query
      ? `<div class="query-box"><strong>Query:</strong> ${escapeHtml(meta.query)}</div>`
      : '';

    return `
<style>
  .export-letterhead {
    display: flex;
    align-items: flex-start;
    justify-content: space-between;
    padding-bottom: 20px;
    border-bottom: 2px solid #4f46e5;
    margin-bottom: 24px;
  }
  .export-logos {
    display: flex;
    align-items: center;
    gap: 16px;
  }
  .umbrella-logo {
    height: 36px;
    width: auto;
    max-width: 180px;
    object-fit: contain;
  }
  .firm-logo {
    height: 36px;
    width: auto;
    max-width: 140px;
    object-fit: contain;
  }
  .logo-divider {
    width: 1px;
    height: 28px;
    background: #e5e7eb;
  }
  .export-meta {
    font-size: 11px;
    color: #6b7280;
    text-align: right;
    font-family: 'Inter', -apple-system, sans-serif;
  }
  .query-box {
    background: #f3f4f6;
    border-left: 3px solid #4f46e5;
    padding: 10px 14px;
    border-radius: 0 6px 6px 0;
    margin-bottom: 24px;
    font-size: 13px;
    color: #374151;
    font-family: 'Inter', -apple-system, sans-serif;
  }
  .export-footer {
    margin-top: 32px;
    padding-top: 12px;
    border-top: 1px solid #e5e7eb;
    display: flex;
    justify-content: space-between;
    font-size: 10px;
    color: #9ca3af;
    font-family: 'Inter', -apple-system, sans-serif;
  }
</style>
<div class="export-letterhead">
  <div class="export-logos">
    <img src="${branding.umbrellaLogoDataUri}" alt="Umbrella" class="umbrella-logo" />
    ${branding.firmLogoDataUri ? '<div class="logo-divider"></div>' : ''}
    ${firmLogoHtml}
  </div>
  <div class="export-meta">
    <div>${escapeHtml(meta.date)}</div>
    ${meta.jurisdiction ? `<div>Jurisdiction: ${escapeHtml(meta.jurisdiction)}</div>` : ''}
  </div>
</div>
${queryHtml}`;
  }

  buildFooterHtml(date: string): string {
    return `
<div class="export-footer">
  <span>Generated by Umbrella Legal AI</span>
  <span>${escapeHtml(date)}</span>
</div>`;
  }

  private async getUmbrellaLogoDataUri(): Promise<string> {
    if (this.umbrellaLogoCache) return this.umbrellaLogoCache;

    // Try bundled asset first (fast, no network)
    const assetPath = path.join(
      process.cwd(),
      'assets',
      'brand',
      'umbrella-logo-light.png',
    );

    if (fs.existsSync(assetPath)) {
      const buf = fs.readFileSync(assetPath);
      this.umbrellaLogoCache = `data:image/png;base64,${buf.toString('base64')}`;
      return this.umbrellaLogoCache;
    }

    // Fallback: resolve relative to this file (monorepo root)
    const altPath = path.join(__dirname, '..', '..', '..', 'assets', 'brand', 'umbrella-logo-light.png');
    if (fs.existsSync(altPath)) {
      const buf = fs.readFileSync(altPath);
      this.umbrellaLogoCache = `data:image/png;base64,${buf.toString('base64')}`;
      return this.umbrellaLogoCache;
    }

    // Last resort: SVG text fallback
    this.umbrellaLogoCache = this.textLogoSvgDataUri();
    return this.umbrellaLogoCache;
  }

  private async fetchLogoAsDataUri(logoUrl: string): Promise<string> {
    // If it's an S3 key stored with s3:// or relative path style, try S3 first
    if (!logoUrl.startsWith('http://') && !logoUrl.startsWith('https://') && !logoUrl.startsWith('data:')) {
      // Treat as S3 key
      const buf = await this.s3.getObject(logoUrl);
      const mime = guessMimeType(logoUrl);
      return `data:${mime};base64,${buf.toString('base64')}`;
    }

    if (logoUrl.startsWith('data:')) return logoUrl;

    // HTTP/HTTPS — fetch via Node
    const { default: https } = await import('https');
    const { default: http } = await import('http');
    const fetch = logoUrl.startsWith('https://') ? https : http;

    return new Promise((resolve, reject) => {
      fetch.get(logoUrl, (res) => {
        const chunks: Buffer[] = [];
        res.on('data', (c: Buffer) => chunks.push(c));
        res.on('end', () => {
          const buf = Buffer.concat(chunks);
          const contentType = res.headers['content-type'] ?? 'image/png';
          resolve(`data:${contentType};base64,${buf.toString('base64')}`);
        });
        res.on('error', reject);
      }).on('error', reject);
    });
  }

  private textLogoSvgDataUri(): string {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="160" height="36"><text x="0" y="28" font-family="Arial,sans-serif" font-size="22" font-weight="700" fill="#4f46e5">☂ Umbrella</text></svg>`;
    return `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  }
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function guessMimeType(url: string): string {
  if (url.match(/\.png$/i)) return 'image/png';
  if (url.match(/\.(jpg|jpeg)$/i)) return 'image/jpeg';
  if (url.match(/\.svg$/i)) return 'image/svg+xml';
  if (url.match(/\.webp$/i)) return 'image/webp';
  return 'image/png';
}
