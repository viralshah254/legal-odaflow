export enum DomainErrorCode {
  // General
  NOT_FOUND = 'NOT_FOUND',
  FORBIDDEN = 'FORBIDDEN',
  VALIDATION_FAILED = 'VALIDATION_FAILED',
  CONFLICT = 'CONFLICT',
  RATE_LIMITED = 'RATE_LIMITED',
  // Credits/billing
  INSUFFICIENT_CREDITS = 'INSUFFICIENT_CREDITS',
  WORKFLOW_BUDGET_EXCEEDED = 'WORKFLOW_BUDGET_EXCEEDED',
  PREMIUM_MODEL_NOT_ALLOWED = 'PREMIUM_MODEL_NOT_ALLOWED',
  TENANT_SPEND_LIMIT_REACHED = 'TENANT_SPEND_LIMIT_REACHED',
  // Workflow
  WORKFLOW_NOT_FOUND = 'WORKFLOW_NOT_FOUND',
  WORKFLOW_ALREADY_CANCELLED = 'WORKFLOW_ALREADY_CANCELLED',
  WORKFLOW_NOT_CANCELLABLE = 'WORKFLOW_NOT_CANCELLABLE',
  // Jurisdiction
  JURISDICTION_NOT_SUPPORTED = 'JURISDICTION_NOT_SUPPORTED',
  JURISDICTION_UNRESOLVED = 'JURISDICTION_UNRESOLVED',
  // Provider
  AI_PROVIDER_UNAVAILABLE = 'AI_PROVIDER_UNAVAILABLE',
  AI_PROVIDER_BUDGET_EXCEEDED = 'AI_PROVIDER_BUDGET_EXCEEDED',
  // Legal
  PROCEDURAL_GATE_FAILED = 'PROCEDURAL_GATE_FAILED',
  VERIFICATION_FAILED = 'VERIFICATION_FAILED',
  FILING_NOT_READY = 'FILING_NOT_READY',
  CITATION_UNVERIFIED = 'CITATION_UNVERIFIED',
  // Security
  TENANT_ISOLATION_VIOLATION = 'TENANT_ISOLATION_VIOLATION',
  ETHICAL_WALL_VIOLATION = 'ETHICAL_WALL_VIOLATION',
  // Idempotency
  IDEMPOTENCY_CONFLICT = 'IDEMPOTENCY_CONFLICT',
}

export class DomainError extends Error {
  constructor(
    public readonly code: DomainErrorCode,
    public readonly message: string,
    public readonly statusCode: number = 400,
    public readonly details?: Record<string, unknown>,
    public readonly retryable: boolean = false,
  ) {
    super(message);
    this.name = 'DomainError';
  }
}
