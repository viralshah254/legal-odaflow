import { Injectable, Logger } from '@nestjs/common';
import { LlmCompletionService } from '@/ai/llm-completion.service';
import { DraftModelRouterService } from '../draft-model-router.service';
import { buildIssueFingerprint, type DraftIssue } from '../contracts/draft-issue';
import type { QualityTier } from '../contracts/model-aliases';
import { DraftJobService } from '../draft-job.service';
import type { CaseRecord } from '@/ai/drafting/contracts/case-record';
import { createHash } from 'crypto';

export interface DefectReportInput {
  jobId: string;
  sections: Array<{ sectionKey: string; sectionType: string; content: string }>;
  verificationIssues: DraftIssue[];
  qualityTier: QualityTier;
  /** Structured CaseRecord for fidelity review against intake. */
  caseRecord?: CaseRecord;
  /** Raw intake narrative. */
  caseDetails?: string;
  documentKind?: string;
  prohibitedAssertions?: string[];
  requiredSections?: string[];
  courtProfileId?: string;
}

export interface DefectReport {
  additionalIssues: DraftIssue[];
}

/**
 * Independent LLM reviewer for draft defects.
 * Prefer CaseRecord + intake grounding over draft-only review.
 */
@Injectable()
export class DraftDefectReportService {
  private readonly logger = new Logger(DraftDefectReportService.name);

  constructor(
    private readonly llm: LlmCompletionService,
    private readonly modelRouter: DraftModelRouterService,
    private readonly jobService: DraftJobService,
  ) {}

  async generateReport(input: DefectReportInput): Promise<DefectReport> {
    // Express stays cheap by default, but it must not be a hole in self-review:
    // when the deterministic pass already found material risk, escalate anyway.
    if (input.qualityTier === 'express' && !this.hasMaterialRisk(input)) {
      return { additionalIssues: [] };
    }

    const model = this.modelRouter.resolveReviewerModel(input.qualityTier);
    const draftSummary = input.sections
      .map((s) => `=== ${s.sectionType.toUpperCase()} ===\n${s.content.slice(0, 800)}`)
      .join('\n\n');

    const existingFingerprints = new Set(input.verificationIssues.map((i) => i.fingerprint));
    const caseRecordBlock = this.buildCaseRecordBlock(input);

    const systemPrompt = `You are an independent legal reviewer. The draft was generated by a different AI system.
Your job is to find defects the drafter may have missed — especially:
- Invented facts not in CaseRecord / intake (including invented insurer denial, doctor qualifications)
- Known CaseRecord values left as [BLANK]
- Unsupported conclusive allegations (negligence, forgery, absence of consent stated as established)
- Wrong party names/roles/terminology or omitted material parties
- Wrong statute section / forum / pecuniary jurisdiction
- Relief/prayer that exceeds pleaded legal tests
- Material adverse facts omitted
- Missing required sections / verification / annexure list

IMPORTANT: Output ONLY valid JSON in this exact format:
{
  "issues": [
    {
      "severity": "high",
      "sectionId": "section_grounds",
      "problem": "The proposition exceeds the verified holding",
      "repairInstruction": "Limit the argument to..."
    }
  ]
}

Severity must be: critical | high | medium | low
Do NOT rewrite any section. Only identify problems.`;

    const userPrompt = `Review this draft document for defects against CaseRecord / intake:

${caseRecordBlock}

DRAFT:
${draftSummary}

Known issues already detected:
${input.verificationIssues.slice(0, 10).map((i) => `- [${i.severity}] ${i.message}`).join('\n') || 'None'}

Prohibited assertions: ${(input.prohibitedAssertions ?? []).join(', ') || 'n/a'}
Required sections: ${(input.requiredSections ?? []).join(', ') || 'n/a'}
`;

    try {
      const completion = await this.llm.complete({
        modelName: model,
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: userPrompt },
        ],
        temperature: 0.1,
        maxTokens: 2000,
      });

      const parsed = this.parseIssues(completion.content ?? '');
      const additionalIssues: DraftIssue[] = [];

      for (const raw of parsed) {
        const message = String(raw.problem ?? raw.message ?? '').trim();
        if (!message) continue;
        const severity = this.mapSeverity(String(raw.severity ?? 'medium'));
        const sectionId = String(raw.sectionId ?? 'document');
        const fingerprint = buildIssueFingerprint(
          'logic',
          sectionId,
          message,
          undefined,
        );
        if (existingFingerprints.has(fingerprint)) continue;
        existingFingerprints.add(fingerprint);
        additionalIssues.push({
          id: `defect_${createHash('sha256').update(fingerprint).digest('hex').slice(0, 10)}`,
          category: 'logic',
          severity,
          message,
          suggestedCorrection: String(raw.repairInstruction ?? raw.repairHint ?? ''),
          sectionId,
          repairableAutomatically: false,
          validator: 'DraftDefectReportService',
          fingerprint,
        });
      }

      void this.jobService; // retained for DI parity with module wiring
      return { additionalIssues };
    } catch (err) {
      this.logger.warn(
        `Defect report failed: ${err instanceof Error ? err.message : String(err)}`,
      );
      return { additionalIssues: [] };
    }
  }

  /**
   * Material risk means an unsupported or unverifiable legal assertion already
   * surfaced deterministically - the case where a second opinion is worth its cost.
   */
  private hasMaterialRisk(input: DefectReportInput): boolean {
    return input.verificationIssues.some(
      (issue) =>
        issue.severity === 'critical' ||
        issue.severity === 'high' ||
        issue.category === 'unsupported_proposition' ||
        issue.category === 'citation',
    );
  }

  private buildCaseRecordBlock(input: DefectReportInput): string {
    const lines: string[] = [];
    if (input.documentKind) lines.push(`Document kind: ${input.documentKind}`);
    if (input.courtProfileId) lines.push(`CourtProfile: ${input.courtProfileId}`);
    if (input.caseDetails) {
      lines.push(`INTAKE (excerpt):\n${input.caseDetails.slice(0, 1500)}`);
    }
    const cr = input.caseRecord;
    if (cr) {
      lines.push(
        `PARTIES:\n${(cr.parties ?? []).map((p) => `- ${p.role}: ${p.name}`).join('\n') || '(none)'}`,
      );
      lines.push(
        `CHRONOLOGY:\n${(cr.chronology ?? []).map((e) => `- ${e.label}: ${e.date ?? '?'}`).join('\n') || '(none)'}`,
      );
      lines.push(
        `MONEY:\n${(cr.moneyRecords ?? []).map((m) => `- ${m.kind}: ${m.amountLabel} (${m.description})`).join('\n') || '(none)'}`,
      );
      lines.push(
        `FACTS:\n${(cr.facts ?? [])
          .slice(0, 20)
          .map((f) => `- [${f.status}] ${f.proposition}`)
          .join('\n') || '(none)'}`,
      );
      const disputed = (cr.facts ?? []).filter((f) => f.status === 'disputed');
      if (disputed.length) {
        lines.push(
          `DISPUTED FACTS (must not be stated as admitted):\n${disputed
            .map((f) => `- ${f.proposition}`)
            .join('\n')}`,
        );
      }
    }
    return lines.join('\n\n') || 'No CaseRecord provided — review draft self-consistency only.';
  }

  private parseIssues(text: string): Array<Record<string, unknown>> {
    try {
      const cleaned = text.replace(/^```json\s*/i, '').replace(/```$/i, '').trim();
      const json = JSON.parse(cleaned);
      if (Array.isArray(json?.issues)) return json.issues;
      if (Array.isArray(json)) return json;
    } catch {
      /* fall through */
    }
    return [];
  }

  private mapSeverity(s: string): DraftIssue['severity'] {
    const n = s.toLowerCase();
    if (n === 'critical') return 'critical';
    if (n === 'high') return 'high';
    if (n === 'low') return 'low';
    return 'medium';
  }
}
