/** Shared red-blocker codes for draft accuracy validators. */

export type AccuracySeverity = 'blocker' | 'warning' | 'info';

export interface AccuracyFinding {
  code: string;
  severity: AccuracySeverity;
  message: string;
  sectionHint?: string;
  repairHint?: string;
  /** Optional diagnostic payload (e.g. validator name, error detail). */
  metadata?: Record<string, unknown>;
}

export interface AccuracyAuditResult {
  findings: AccuracyFinding[];
  passed: boolean;
}

export function blockersOnly(findings: AccuracyFinding[]): AccuracyFinding[] {
  return findings.filter((f) => f.severity === 'blocker');
}

export function auditPassed(findings: AccuracyFinding[]): boolean {
  return !findings.some((f) => f.severity === 'blocker');
}

