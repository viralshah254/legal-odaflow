// ── Source tier ───────────────────────────────────────────────────────────────

export type SourceTier = 'OFFICIAL' | 'CURATED' | 'AGGREGATOR' | 'WEB';

// ── Evidence passage ──────────────────────────────────────────────────────────

/**
 * A narrow text passage linked to a single authority.
 * Every proposition generated by the synthesis model must reference an evidenceId.
 */
export interface EvidencePassage {
  /** Stable reference ID — must match any ClaimBlock.evidenceIds entry. */
  evidenceId: string;
  authorityId: string;
  paragraph?: string;
  page?: number;
  text: string;
  sourceHash: string;
  propositionTags: string[];
  sourceUrl?: string;
  sourceTier: SourceTier;
  retrievalScore: number;
  classification?: PassageClassification;
  classificationConfidence?: number;
  provenance?: SourceProvenance;
  admission?: EvidenceAdmissionDecision;
}

// ── Statute evidence ──────────────────────────────────────────────────────────

export interface EvidenceStatute {
  evidenceId: string;
  canonicalAuthorityId?: string;
  actId: string;
  section: string;
  heading?: string;
  actName?: string;
  actYear?: number;
  text: string;
  sourceHash: string;
  effectiveDate?: string;
  effectiveFrom?: string;
  effectiveTo?: string;
  /** Curated registry status evaluated against `asOfDate`. */
  registryStatus?: 'active' | 'repealed' | 'superseded' | 'amended';
  versionSourceUrl?: string;
  /** When true, the provision has been superseded by a successor enactment. */
  superseded?: boolean;
  successorActId?: string;
  successorSection?: string;
  sourceUrl?: string;
  provenance?: SourceProvenance;
  admission?: EvidenceAdmissionDecision;
}

export interface SourceSnapshot {
  authorityId: string;
  canonicalAuthorityId?: string;
  sourceName?: string;
  sourceTier?: SourceTier;
  citation?: string;
  neutralCitation?: string;
  sourceUrl?: string;
  retrievedAt: string;
  documentHash: string;
  extractorVersion: string;
  provenance?: SourceProvenance;
  admission?: EvidenceAdmissionDecision;
  pinpoint?: { page?: number; paragraph?: string; sectionPath?: string };
  statuteVersion?: {
    actId: string;
    section: string;
    effectiveFrom?: string;
    effectiveTo?: string;
  };
}

// ── Case evidence ─────────────────────────────────────────────────────────────

export interface EvidenceCase {
  evidenceId: string;
  authorityId: string;
  canonicalAuthorityId?: string;
  title: string;
  citation: string;
  court: string;
  decidedDate?: string;
  sourceUrl?: string;
  sourceName?: string;
  sourceTier?: SourceTier;
  practiceAreas?: string[];
  topics?: string[];
  benchStrength?: number;
  passages: EvidencePassage[];
  /** overruled | distinguished | followed | affirmed | doubted | explained */
  subsequentTreatment?: string;
  /** True only when treatment came from a reviewed/source-attributed record. */
  treatmentVerified?: boolean;
  treatmentSourceName?: string;
  treatmentSourceUrl?: string;
  controllingJurisdiction?: string;
  userAuthorityStatus?: UserAuthorityStatus;
  proceduralPosture?: ProceduralPostureMetadata;
  precedent?: PrecedentMetadata;
  admission?: EvidenceAdmissionDecision;
  provenance?: SourceProvenance;
}

