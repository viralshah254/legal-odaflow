export interface PackEvidenceGap {
  issueId: string;
  issue: string;
  missingDimension: string;
  searchedAt: string;
}

// ── Evidence pack ─────────────────────────────────────────────────────────────

/**
 * Immutable evidence pack passed to the synthesis model.
 *
 * The synthesis model receives a locked pack and must reference evidenceIds
 * for every proposition. It must never generate citation strings itself —
 * those are inserted from database metadata after verification.
 */
export interface LegalEvidencePack {
  evidencePackId: string;
  version: string;
  jurisdiction: string;
  /** ISO-8601 date. Displayed as "Research current as of: 27 June 2026" */
  asOfDate: string;
  statutes: EvidenceStatute[];
  authorities: EvidenceCase[];
  officialMaterials: OfficialMaterialEvidence[];
  sourceSnapshots: SourceSnapshot[];
  matterFacts: MatterFact[];
  unresolvedGaps: PackEvidenceGap[];
}

// ── Unregistered evidence error ───────────────────────────────────────────────

export class UnsupportedEvidenceReferenceError extends Error {
  constructor(evidenceId: string) {
    super(
      `Proposition references evidenceId "${evidenceId}" which is not present in the evidence pack. ` +
        'Case names, citations, and URLs must be sourced from the evidence pack, not generated by the model.',
    );
    this.name = 'UnsupportedEvidenceReferenceError';
  }
}

// ── Service ───────────────────────────────────────────────────────────────────

@Injectable()
export class LegalEvidencePackService {
  private readonly logger = new Logger(LegalEvidencePackService.name);
  private static readonly SCHEMA_VERSION = 'v2';
  private readonly evidenceAdmission = new EvidenceAdmissionService();
  private readonly passageClassification = new PassageClassificationService();

  /**
   * Builds a LegalEvidencePack from retrieved authorities.
   * Builds immutable snapshots from the exact text used for verification.
   */
  buildFromAuthorities(input: {
    jurisdiction: string;
    authorities: Array<{
      id: string;
      title: string;
      citation?: string | null;
      neutralCitation?: string | null;
      sourceTier?: string;
      authorityType?: string;
      sourceName?: string;
      summary?: string | null;
      fullText?: string | null;
      sourceUrl?: string | null;
      treatmentStatus?: string | null;
      controllingJurisdiction?: string | null;
      decisionYear?: number | null;
      decisionDate?: string | Date | null;
      courtTierRank?: number | null;
      court?: string | null;
      practiceAreas?: string[];
      topics?: string[];
      paragraph?: string | null;
      page?: number | null;
      actName?: string | null;
      actYear?: number | null;
      section?: string | null;
      heading?: string | null;
      sourcePassages?: Array<{
        text: string;
        paragraph?: string;
        page?: number;
        sourcePinpoint?: boolean;
        classification?: PassageClassification;
        classificationConfidence?: number;
      }>;
      sourceProvenance?: SourceProvenance;
      userAuthorityStatus?: UserAuthorityStatus;
      proceduralPosture?: ProceduralPostureMetadata;
      precedent?: PrecedentMetadata;
    }>;
    matterFacts?: MatterFact[];
    lawAsOfDate?: string;
  }): LegalEvidencePack {
    const statutes: EvidenceStatute[] = [];
    const cases: EvidenceCase[] = [];
    const officials: OfficialMaterialEvidence[] = [];
    const sourceSnapshots: SourceSnapshot[] = [];

    for (const auth of this.canonicalizeAuthorities(input.authorities)) {
      const evidenceId = `EVD_${auth.id.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase().slice(0, 20)}`;
      const canonicalAuthorityId = this.canonicalAuthorityId(auth);
      const isStatute =
        auth.sourceTier === 'primary' || auth.sourceTier === 'seed';
      const isCaseLaw = auth.sourceTier === 'case_law';
      const exactText = auth.fullText ?? auth.summary ?? '';
      const inferredAuthorityType =
        auth.authorityType ?? (isCaseLaw ? 'case' : isStatute ? 'statute' : 'other');
      const classifiedPassages = (auth.sourcePassages?.length
        ? auth.sourcePassages
        : [{ text: exactText, paragraph: auth.paragraph ?? undefined, page: auth.page ?? undefined }]
      ).map((passage) => {
        if (passage.classification && passage.classification !== 'UNKNOWN') return passage;
        const classified = this.passageClassification.classify(
          passage.text,
          inferredAuthorityType,
        );
        return {
          ...passage,
          classification: classified.classification,
          classificationConfidence: classified.confidence,
        };
      });
      const sourceHash = this.hashText(exactText);
      const mappedSourceTier = this.mapSourceTier(
        auth.sourceTier,
        auth.sourceName,
        auth.sourceUrl,
        auth.id,
      );
      const admission = this.evidenceAdmission.admit({
        authority: {
          ...auth,
          authorityType: inferredAuthorityType,
          sourcePassages: classifiedPassages,
        },
        intendedUse: 'LEGAL_RULE',
        passageClassification: classifiedPassages[0]?.classification,
      });
      const snapshot: SourceSnapshot = {
        authorityId: auth.id,
        canonicalAuthorityId,
        sourceName: auth.sourceName,
        sourceTier: mappedSourceTier,
        citation: auth.citation ?? undefined,
        neutralCitation: auth.neutralCitation ?? undefined,
        sourceUrl: auth.sourceUrl ?? undefined,
        retrievedAt: new Date().toISOString(),
        documentHash: sourceHash,
        extractorVersion: LegalEvidencePackService.SCHEMA_VERSION,
        provenance: auth.sourceProvenance,
        admission,
        pinpoint:
          auth.paragraph || auth.page
            ? { paragraph: auth.paragraph ?? undefined, page: auth.page ?? undefined }
            : undefined,
      };

      if (isStatute) {
        const registryStatute = this.matchIndiaStatute({
          title: auth.title,
          citation: auth.citation,
          id: auth.id,
        });
        const section =
          auth.section?.trim() ||
          this.extractSection(auth.title) ||
          this.extractSection(auth.citation ?? '') ||
          this.extractSection(auth.id);
        const versionMeta = this.resolveIndiaStatuteVersion({
          title: auth.title,
          citation: auth.citation,
          id: auth.id,
          treatmentStatus: auth.treatmentStatus,
          lawAsOfDate: input.lawAsOfDate ?? new Date().toISOString().split('T')[0],
        });
        statutes.push({
          evidenceId,
          canonicalAuthorityId,
          actId: registryStatute?.id ?? auth.id,
          section,
          heading: auth.title,
          actName:
            auth.actName ??
            registryStatute?.fullName ??
            auth.title.match(/^(.+?Act(?:,\s*\d{4})?)/i)?.[1] ??
            this.humanizeAuthorityId(auth.id),
          actYear:
            auth.actYear ??
            (Number(auth.title.match(/\b(18|19|20)\d{2}\b/)?.[0] || 0) || undefined),
          text: exactText,
          sourceHash,
          sourceUrl: auth.sourceUrl ?? undefined,
          effectiveDate: versionMeta.effectiveDate,
          effectiveFrom: versionMeta.effectiveFrom,
          effectiveTo: versionMeta.effectiveTo,
          superseded: versionMeta.superseded,
          successorActId: versionMeta.successorActId,
          registryStatus: versionMeta.registryStatus,
          versionSourceUrl: versionMeta.versionSourceUrl,
          provenance: auth.sourceProvenance,
          admission,
        });
        sourceSnapshots.push({
          ...snapshot,
          statuteVersion: {
            actId: registryStatute?.id ?? auth.id,
            section,
            effectiveFrom: versionMeta.effectiveFrom,
            effectiveTo: versionMeta.effectiveTo,
          },
        });
      } else if (isCaseLaw) {
        cases.push({
          evidenceId,
          authorityId: auth.id,
          canonicalAuthorityId,
          title: auth.title,
          citation: auth.citation ?? '',
          court: auth.court ?? auth.sourceName ?? 'Unknown Court',
          decidedDate:
            auth.decisionDate instanceof Date
              ? auth.decisionDate.toISOString()
              : auth.decisionDate ?? (auth.decisionYear ? `${auth.decisionYear}` : undefined),
          sourceUrl: auth.sourceUrl ?? undefined,
          sourceName: auth.sourceName,
          sourceTier: mappedSourceTier,
          practiceAreas: auth.practiceAreas,
          topics: auth.topics,
          benchStrength: typeof auth.courtTierRank === 'number' ? Math.max(1, 3 - auth.courtTierRank) : undefined,
          subsequentTreatment: auth.treatmentStatus ?? undefined,
          treatmentVerified:
            Boolean(auth.treatmentStatus) && mappedSourceTier === 'CURATED',
          treatmentSourceName:
            Boolean(auth.treatmentStatus) && mappedSourceTier === 'CURATED'
              ? auth.sourceName
              : undefined,
          treatmentSourceUrl:
            Boolean(auth.treatmentStatus) && mappedSourceTier === 'CURATED'
              ? auth.sourceUrl ?? undefined
              : undefined,
          controllingJurisdiction: auth.controllingJurisdiction ?? input.jurisdiction,
          userAuthorityStatus: auth.userAuthorityStatus,
          proceduralPosture: auth.proceduralPosture,
          precedent: auth.precedent,
          admission,
          provenance: auth.sourceProvenance,
          passages: classifiedPassages.map((sourcePassage, index) => ({
              evidenceId: `${evidenceId}_P1`,
              authorityId: auth.id,
              paragraph: sourcePassage.paragraph,
              page: sourcePassage.page,
              text: sourcePassage.text,
              sourceHash: this.hashText(sourcePassage.text),
              propositionTags: [],
              sourceTier: mappedSourceTier,
              retrievalScore: auth.fullText ? 1.0 : 0.45,
              sourceUrl: auth.sourceUrl ?? undefined,
              classification: sourcePassage.classification,
              classificationConfidence: sourcePassage.classificationConfidence,
              provenance: auth.sourceProvenance,
              admission,
              ...(index > 0 ? { evidenceId: `${evidenceId}_P${index + 1}` } : {}),
            })),
        });
        sourceSnapshots.push(snapshot);
      } else {
        officials.push({
          evidenceId,
          canonicalAuthorityId,
          title: auth.title,
          sourceName: auth.sourceName ?? 'Unknown',
          text: exactText,
          sourceHash,
          sourceUrl: auth.sourceUrl ?? undefined,
          provenance: auth.sourceProvenance,
          admission,
        });
        sourceSnapshots.push(snapshot);
      }
    }

    return {
      evidencePackId: randomUUID(),
      version: LegalEvidencePackService.SCHEMA_VERSION,
      jurisdiction: input.jurisdiction,
      asOfDate: input.lawAsOfDate ?? new Date().toISOString().split('T')[0],
      statutes,
      authorities: cases,
      officialMaterials: officials,
      sourceSnapshots,
      matterFacts: input.matterFacts ?? [],
      unresolvedGaps: [],
    };
  }

  build(input: Parameters<LegalEvidencePackService['buildFromAuthorities']>[0]): LegalEvidencePack {
    return this.buildFromAuthorities(input);
  }

  /**
   * Validates that all evidenceIds referenced in propositions exist in the pack.
   * Call before rendering the final document to the user.
   */
  validatePropositionReferences(
    propositions: Array<{ claimId: string; evidenceIds: string[] }>,
    pack: LegalEvidencePack,
  ): void {
    const registered = this.buildEvidenceIndex(pack);

    for (const proposition of propositions) {
      for (const evidenceId of proposition.evidenceIds) {
        if (!registered.has(evidenceId)) {
          throw new UnsupportedEvidenceReferenceError(evidenceId);
        }
      }
    }
  }

  private buildEvidenceIndex(pack: LegalEvidencePack): Set<string> {
    const ids = new Set<string>();
    for (const s of pack.statutes) ids.add(s.evidenceId);
    for (const c of pack.authorities) {
      ids.add(c.evidenceId);
      for (const p of c.passages) ids.add(p.evidenceId);
    }
    for (const o of pack.officialMaterials) ids.add(o.evidenceId);
    return ids;
  }

  private extractSection(title: string): string {
    const match = title.match(
      /(?:section|s\.|art\.?|article|[-_](?:s|sec|section))\s*[-_.:]?\s*(\d+[a-zA-Z0-9()/-]*)/i,
    );
    return match ? match[1] : '';
  }

  private humanizeAuthorityId(id: string): string {
    return id
      .replace(/^statute[-_](?:in|india)[-_]/i, '')
      .replace(/[-_](?:s|sec|section)[-_]?\d+[a-zA-Z0-9()/-]*$/i, '')
      .split(/[-_]+/)
      .filter(Boolean)
      .map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
      .join(' ');
  }

  private canonicalizeAuthorities<T extends {
    id: string;
    title: string;
    citation?: string | null;
    neutralCitation?: string | null;
    sourceTier?: string;
    sourceName?: string;
    sourceUrl?: string | null;
    fullText?: string | null;
    summary?: string | null;
  }>(authorities: T[]): T[] {
    const canonical = new Map<string, T>();
    for (const authority of authorities) {
      const key = this.canonicalAuthorityId(authority);
      const existing = canonical.get(key);
      if (!existing) {
        canonical.set(key, authority);
        continue;
      }

      const authorityRank = this.sourceRank(authority);
      const existingRank = this.sourceRank(existing);
      const preferred = authorityRank > existingRank ? authority : existing;
      const alternate = preferred === authority ? existing : authority;
      canonical.set(key, {
        ...alternate,
        ...preferred,
        fullText:
          (preferred.fullText?.length ?? 0) >= (alternate.fullText?.length ?? 0)
            ? preferred.fullText
            : alternate.fullText,
        summary: preferred.summary ?? alternate.summary,
        neutralCitation: preferred.neutralCitation ?? alternate.neutralCitation,
        citation: preferred.citation ?? alternate.citation,
      });
    }
    return [...canonical.values()];
  }

  private canonicalAuthorityId(authority: {
    id: string;
    title: string;
    citation?: string | null;
    neutralCitation?: string | null;
    sourceTier?: string;
  }): string {
    const normalizedCitation = (authority.citation ?? authority.neutralCitation ?? '')
      .toLowerCase()
      .replace(/\bversus\b|\bvs?\.?\b/g, 'v')
      .replace(/[^a-z0-9]/g, '');
    const identity = normalizedCitation
      ? `citation:${normalizedCitation}`
      : `title:${authority.title.toLowerCase().replace(/[^a-z0-9]/g, '')}:${authority.sourceTier ?? ''}`;
    return `AUTH_${createHash('sha256').update(identity).digest('hex').slice(0, 20).toUpperCase()}`;
  }

  private sourceRank(authority: {
    id: string;
    sourceTier?: string;
    sourceName?: string;
    sourceUrl?: string | null;
  }): number {
    const tier = this.mapSourceTier(
      authority.sourceTier,
      authority.sourceName,
      authority.sourceUrl,
      authority.id,
    );
    return tier === 'OFFICIAL' ? 4 : tier === 'CURATED' ? 3 : tier === 'AGGREGATOR' ? 2 : 1;
  }

  /** Resolve version/current-law metadata from the curated India statute registry. */
  private resolveIndiaStatuteVersion(input: {
    title: string;
    citation?: string | null;
    id: string;
    treatmentStatus?: string | null;
    lawAsOfDate: string;
  }): {
    effectiveDate?: string;
    effectiveFrom?: string;
    effectiveTo?: string;
    superseded: boolean;
    successorActId?: string;
    registryStatus?: 'active' | 'repealed' | 'superseded' | 'amended';
    versionSourceUrl?: string;
  } {
    const statute = this.matchIndiaStatute(input);
    const explicitSuperseded =
      input.treatmentStatus === 'superseded' || input.treatmentStatus === 'repealed';
    if (statute) {
      const beforeCommencement =
        Boolean(statute.effectiveFrom) && input.lawAsOfDate < statute.effectiveFrom!;
      const afterEnd = Boolean(statute.effectiveTo) && input.lawAsOfDate > statute.effectiveTo!;
      const registrySuperseded =
        afterEnd ||
        ((statute.status === 'repealed' || statute.status === 'superseded') &&
          (!statute.effectiveTo || input.lawAsOfDate.slice(0, 4) >= String(statute.repealYear ?? 0)));
      return {
        effectiveDate: statute.effectiveFrom,
        effectiveFrom: statute.effectiveFrom,
        effectiveTo: statute.effectiveTo,
        superseded: explicitSuperseded || registrySuperseded || beforeCommencement,
        successorActId: statute.repealedBy
          ? (IN_STATUTES.find((candidate) => candidate.id === statute.repealedBy)?.shortName ??
            statute.repealedBy)
          : undefined,
        registryStatus: statute.status ?? 'active',
        versionSourceUrl: statute.sourceUrl,
      };
    }
    return {
      superseded: explicitSuperseded,
    };
  }

  private matchIndiaStatute(input: {
    title: string;
    citation?: string | null;
    id: string;
  }): StatuteEntry | undefined {
    const normalize = (value: string) =>
      value.toLowerCase().replace(/[^a-z0-9]+/g, ' ').replace(/\s+/g, ' ').trim();
    const blob = ` ${normalize(`${input.id} ${input.title} ${input.citation ?? ''}`)} `;
    return IN_STATUTES
      .map((statute) => {
        const candidates = [
          statute.id,
          statute.fullName,
          statute.shortName,
          ...statute.acronyms,
          ...statute.searchAliases,
        ]
          .map(normalize)
          .filter((candidate) => candidate.length >= 3);
        const score = Math.max(
          0,
          ...candidates.map((candidate) =>
            blob.includes(` ${candidate} `) ? candidate.length : 0,
          ),
        );
        return { statute, score };
      })
      .filter((candidate) => candidate.score > 0)
      .sort((a, b) => b.score - a.score)[0]?.statute;
  }

  private mapSourceTier(
    tier?: string,
    sourceName?: string,
    sourceUrl?: string | null,
    authorityId?: string,
  ): SourceTier {
    const provenance = `${sourceName ?? ''} ${sourceUrl ?? ''} ${authorityId ?? ''}`.toLowerCase();
    switch (tier) {
      case 'primary':
      case 'seed':
        return 'OFFICIAL';
      case 'case_law':
        if (/\bescr\b|e-scr|scr\.sci\.gov\.in|supremecourt\.gov\.in/.test(provenance)) {
          return 'OFFICIAL';
        }
        if (/india-corpus|curated|human-reviewed/.test(provenance)) {
          return 'CURATED';
        }
        return 'AGGREGATOR';
      case 'web':
        return 'WEB';
      default:
        return 'AGGREGATOR';
    }
  }

  private hashText(text: string): string {
    return createHash('sha256').update(text).digest('hex');
  }
}
