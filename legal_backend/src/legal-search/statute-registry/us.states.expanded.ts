import { StatuteEntry } from './types';

function stateAct(
  id: string,
  jurisdiction: string,
  shortName: string,
  fullName: string,
  findLawSlug: string,
): StatuteEntry {
  return {
    id,
    countryCode: 'US',
    jurisdiction,
    acronyms: [id, id.replace(/-/g, ' ')],
    fullName,
    shortName,
    practiceAreas: ['state_law'],
    searchAliases: [`${jurisdiction} ${fullName}`],
    sourceUrl: `https://codes.findlaw.com/${findLawSlug}/`,
    externalId: id.replace(/-/g, '_'),
    ingestPriority: 3,
  };
}

